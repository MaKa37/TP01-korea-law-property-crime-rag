-- [1] 길이 구간별 분포 (버킷을 보고 어디서 끊을지 판단)
SELECT
    width_bucket(length(content), 0, 600, 12) AS len_bucket,
    MIN(length(content)) AS min_len,
    MAX(length(content)) AS max_len,
    COUNT(*) AS chunk_count
FROM legal_chunks
WHERE doc_type = 'prec'
  AND (chunk_id LIKE '%\_head' OR chunk_id LIKE '%\_head\_%')
  AND content ~ '\[판결요지\]\s*$'
GROUP BY len_bucket
ORDER BY len_bucket;

