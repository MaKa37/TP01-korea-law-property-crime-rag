-- check_expc_duplicates.sql
-- expc는 prec와 달리 심급 구조가 없어, 같은 안건명이 여러 expc_id로 존재하면
-- 거의 확실히 재수집 중복입니다. 규모와 실제 내용 동일 여부를 확인합니다.
-- ============================================================================

-- [1] 전체 규모: 고유 안건명(title) 수 vs 고유 expc_id(doc_id) 수
WITH conclusion_groups AS (
    SELECT title, doc_id
    FROM legal_chunks
    WHERE doc_type = 'expc'
      AND chunk_id LIKE '%\_conclusion'
)
SELECT
    COUNT(DISTINCT title)  AS unique_agenda_titles,
    COUNT(DISTINCT doc_id) AS unique_expc_ids,
    COUNT(DISTINCT doc_id) - COUNT(DISTINCT title) AS estimated_duplicate_expc_ids
FROM conclusion_groups;

-- 7745 8802 1057

-- [2] 중복 규모 상위 안건 재확인 (몇 개 안건이 대부분의 중복을 차지하는지)
WITH conclusion_groups AS (
    SELECT title, doc_id
    FROM legal_chunks
    WHERE doc_type = 'expc'
      AND chunk_id LIKE '%\_conclusion'
)
SELECT title, COUNT(*) AS doc_id_count
FROM conclusion_groups
GROUP BY title
HAVING COUNT(*) > 1
ORDER BY doc_id_count DESC
LIMIT 20;

