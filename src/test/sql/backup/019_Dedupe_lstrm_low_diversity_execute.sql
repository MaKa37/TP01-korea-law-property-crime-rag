-- [1] 삭제 대상 chunk_id 백업 (전체 행)
CREATE TABLE lstrm_dedup_backup_20260809 AS
SELECT lc.*
FROM legal_chunks lc
JOIN (
    WITH candidate_titles AS (
        SELECT title
        FROM legal_chunks
        WHERE doc_type = 'lstrm'
        GROUP BY title
        HAVING COUNT(*) >= 5
    ),
    def_extract AS (
        SELECT lc2.chunk_id, lc2.title,
               regexp_replace(lc2.content, '^.*?정의: (.*?)(\n출처:.*)?$', '\1', 's') AS definition_text
        FROM legal_chunks lc2
        JOIN candidate_titles ct ON lc2.title = ct.title
        WHERE lc2.doc_type = 'lstrm'
    ),
    diversity_check AS (
        SELECT title,
               COUNT(*) AS total,
               COUNT(DISTINCT definition_text) AS distinct_defs
        FROM def_extract
        GROUP BY title
    ),
    target_titles AS (
        -- 다양성 50% 미만 = 같은 정의가 절반 넘게 반복되는 그룹만 표적
        SELECT title FROM diversity_check
        WHERE 100.0 * distinct_defs / total < 50
    ),
    ranked AS (
        SELECT de.chunk_id, de.title, de.definition_text,
               ROW_NUMBER() OVER (
                   PARTITION BY de.title, de.definition_text
                   ORDER BY de.chunk_id ASC
               ) AS rn
        FROM def_extract de
        JOIN target_titles tt ON de.title = tt.title
    )
    SELECT chunk_id FROM ranked WHERE rn > 1
) dup ON lc.chunk_id = dup.chunk_id
WHERE lc.doc_type = 'lstrm';


-- [2] 백업 건수 확인
SELECT COUNT(*) AS backed_up_chunks
FROM lstrm_dedup_backup_20260809;

