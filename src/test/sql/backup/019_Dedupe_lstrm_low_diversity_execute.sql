-- [3] 대상 title이 몇 개나 되는지, 어떤 것들인지 미리 확인 (삭제 전 검토용)
WITH candidate_titles AS (
    SELECT title
    FROM legal_chunks
    WHERE doc_type = 'lstrm'
    GROUP BY title
    HAVING COUNT(*) >= 5
),
def_extract AS (
    SELECT lc.chunk_id, lc.title,
           regexp_replace(lc.content, '^.*?정의: (.*?)(\n출처:.*)?$', '\1', 's') AS definition_text
    FROM legal_chunks lc
    JOIN candidate_titles ct ON lc.title = ct.title
    WHERE lc.doc_type = 'lstrm'
)
SELECT title,
       COUNT(*) AS total,
       COUNT(DISTINCT definition_text) AS distinct_defs,
       ROUND(100.0 * COUNT(DISTINCT definition_text) / COUNT(*), 1) AS diversity_pct
FROM def_extract
GROUP BY title
HAVING 100.0 * COUNT(DISTINCT definition_text) / COUNT(*) < 50
ORDER BY total DESC;

