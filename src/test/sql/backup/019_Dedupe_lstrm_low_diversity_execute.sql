-- (title, 정의문) 조합별로 대표 1건만 남기고 나머지를 정리합니다.
-- 예: 불이익조치(12.7%), 스토킹(32.4%), 성폭력(32.7%) 등
-- 순서대로 한 스텝씩 확인하면서 진행하세요.
