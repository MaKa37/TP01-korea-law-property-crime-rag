-- [2] 중복이 가장 심한 사건번호 Top 50 (doc_id가 몇 개나 겹치는지)
WITH case_groups AS (
    SELECT DISTINCT
        regexp_replace(title, '^판례 \[([^\]]+)\].*$', '\1') AS case_no,
        doc_id
    FROM legal_chunks
    WHERE doc_type = 'prec'
)
SELECT case_no, COUNT(*) AS doc_id_count, array_agg(doc_id) AS doc_ids
FROM case_groups
GROUP BY case_no
HAVING COUNT(*) > 1
ORDER BY doc_id_count DESC, case_no
LIMIT 50;

