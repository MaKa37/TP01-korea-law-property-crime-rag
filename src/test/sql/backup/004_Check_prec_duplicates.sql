-- 판례 title의 사건번호([ ] 안)를 기준으로 doc_id 중복 규모를 확인합니다.
-- ============================================================================

-- [1] 전체 규모: 고유 사건번호 수 vs 고유 doc_id 수
--     (unique_doc_ids - unique_case_numbers) 가 크면 클수록 중복이 심각한 것
WITH case_groups AS (
    SELECT DISTINCT
        regexp_replace(title, '^판례 \[([^\]]+)\].*$', '\1') AS case_no,
        doc_id
    FROM legal_chunks
    WHERE doc_type = 'prec'
)
SELECT
    COUNT(DISTINCT case_no) AS unique_case_numbers,
    COUNT(DISTINCT doc_id)  AS unique_doc_ids,
    COUNT(DISTINCT doc_id) - COUNT(DISTINCT case_no) AS estimated_duplicate_doc_ids
FROM case_groups;

