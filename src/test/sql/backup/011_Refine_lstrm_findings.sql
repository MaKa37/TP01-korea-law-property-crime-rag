-- [1] "대통령령/총리령/부령으로 정하는 ~" 류 보일러플레이트 위임규정 전체 규모
--     (법령용어가 아니라 입법 관용구로 의심되는 것들)
SELECT COUNT(*) AS boilerplate_chunk_count,
       COUNT(DISTINCT title) AS boilerplate_unique_titles
FROM legal_chunks
WHERE doc_type = 'lstrm'
  AND title ~ '^법령용어: (대통령령|총리령|부령|[가-힣]+부령|[가-힣]+령)으로 정하는';

-- 13473	6079

-- [2] 진짜 동명이의 용어 하나를 골라 실제 정의(content) 차이 확인
--     - "성희롱"은 여러 법에서 다르게 정의될 가능성이 높은 대표 사례
SELECT chunk_id, title, content
FROM legal_chunks
WHERE doc_type = 'lstrm' AND title = '법령용어: 성희롱'
ORDER BY chunk_id
LIMIT 8;

