-- [1] 전체 규모
SELECT
    COUNT(*) FILTER (WHERE content ~ '\[판결요지\]\s*$') AS empty_head_count,
    COUNT(*) AS total_head_chunks
FROM legal_chunks
WHERE doc_type = 'prec'
  AND (chunk_id LIKE '%\_head' OR chunk_id LIKE '%\_head\_%');

