-- [3] 같은 사건(case_no)에 내용 있는 버전(주로 대법원 '도' 사건)이 있는지 확인
--     -> 있다면 "완전 정보 손실"은 아니고, 검색에서 빈 청크만 걸러내면 됨
--     [수정] 상관 서브쿼리(EXISTS) 대신 GROUP BY 집계로 재작성했습니다.
--     기존 버전은 빈 head 1건마다 prec 전체(66만 건)를 재스캔하며 정규식을
--     다시 계산해서 사실상 끝나지 않았습니다. 이 버전은 head 청크 집합을
--     딱 한 번만 훑고 집계만 합니다.
WITH head_info AS (
    SELECT
        regexp_replace(title, '^판례 \[([^\]]+)\].*$', '\1') AS case_no,
        (content ~ '\[판결요지\]\s*$') AS is_empty
    FROM legal_chunks
    WHERE doc_type = 'prec'
      AND (chunk_id LIKE '%\_head' OR chunk_id LIKE '%\_head\_%')
),
case_summary AS (
    SELECT
        case_no,
        COUNT(*) FILTER (WHERE is_empty)     AS empty_count,
        COUNT(*) FILTER (WHERE NOT is_empty) AS nonempty_count
    FROM head_info
    GROUP BY case_no
)
SELECT
    SUM(empty_count) AS empty_cases,
    SUM(CASE WHEN empty_count > 0 AND nonempty_count > 0 THEN empty_count ELSE 0 END)
        AS empty_with_nonempty_sibling
FROM case_summary;

